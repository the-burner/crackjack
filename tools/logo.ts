const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ICONS = path.join(REPO, 'public/assets/icons');

/** Catppuccin Mocha, for the icon. */
const MOCHA = { base: '#1e1e2e', mauve: '#cba6f7', peach: '#fab387' };
const PNG_SIZES = [96, 180, 192, 512];

/** A point of a crack: `[x, y, width]`. */
type CrackPoint = readonly [x: number, y: number, width: number];
type Crack = readonly CrackPoint[];

/** A crack as points `[x, y, width]`: wide where it enters, thin at the tip. */
export function crackPolygon(points: Crack): string {
  const left: string[] = [];
  const right: string[] = [];
  points.forEach(([x, y, w], i) => {
    const [ax, ay] = points[Math.max(0, i - 1)];
    const [bx, by] = points[Math.min(points.length - 1, i + 1)];
    const len = Math.hypot(bx - ax, by - ay) || 1;
    const nx = -(by - ay) / len;
    const ny = (bx - ax) / len;
    left.push(`${+(x + (nx * w) / 2).toFixed(1)},${+(y + (ny * w) / 2).toFixed(1)}`);
    right.unshift(`${+(x - (nx * w) / 2).toFixed(1)},${+(y - (ny * w) / 2).toFixed(1)}`);
  });
  return `<polygon points="${left.concat(right).join(' ')}"/>`;
}

/** `body` with the cracks cut out of it. */
function cracked(
  id: string,
  body: string,
  cracks: readonly Crack[],
  [x, y, width, height]: readonly [number, number, number, number],
): string {
  return (
    `<mask id="${id}" maskUnits="userSpaceOnUse" x="${x}" y="${y}" width="${width}" height="${height}">` +
    `<rect x="${x}" y="${y}" width="${width}" height="${height}" fill="#fff" stroke="none"/>` +
    `<g fill="#000" stroke="none">${cracks.map(crackPolygon).join('')}</g></mask>` +
    `<g mask="url(#${id})">${body}</g>`
  );
}

