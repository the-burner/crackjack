// Draws the Crackjack logo: the CJ app icon (SVG and the PNG sizes iOS and the
// manifest use) and the in-app "Crackjack" wordmark. Usage: npm run logo
//
// Letters are drawn as rounded strokes rather than set in a font, so the crack
// lines up with them exactly. A crack is a tapered polygon cut out of the
// letters with a mask.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
