self.addEventListener('install', (e) => {
  // Cache everything, then activate immediately.
  e.waitUntil(
    caches.open(CACHE)
      .then((c) => c.addAll(ASSETS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (e) => {
  // Drop caches from older versions and take control of open pages.
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  // Cache-first: the app is fully static, so a cache hit is always correct offline.
  e.respondWith(
    caches.match(req).then((hit) => {
      if (hit) return hit;
      // Cache miss (partial install, version-bump gap, or storage eviction): fetch
      // and write a good response back so the file survives the next offline launch.
      return fetch(req).then((res) => {
        if (res && res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
        }
        return res;
      }).catch(() => {
        // Offline and uncached: for a page navigation, fall back to the app shell.
        if (req.mode === 'navigate') return caches.match('./');
        return Response.error();
      });
    })
  );
});
